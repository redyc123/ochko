/** Кириллица, совпадающая по начертанию с латиницей. */
const ALIASES: Readonly<Record<string, string>> = {
  А: 'A',
  В: 'B',
  Е: 'E',
  К: 'K',
  М: 'M',
  Н: 'H',
  О: 'O',
  Р: 'P',
  С: 'C',
  Т: 'T',
  Х: 'X',
  '«': '"',
  '»': '"',
  '“': '"',
  '”': '"',
  '—': '-',
  '–': '-',
};

/** Столбцы глифа: бит0 = верхняя строка. */
const GLYPHS = new Map<string, Uint8Array>();
for (const [ch, rows] of Object.entries(ROWS)) {
  const lines = rows.split(' ');
  const cols = new Uint8Array(GLYPH_WIDTH);
  lines.forEach((line, y) => {
    for (let x = 0; x < GLYPH_WIDTH; x += 1) {
      if (line[x] === '#') cols[x]! |= 1 << y;
    }
  });
  GLYPHS.set(ch, cols);
}

/** Текст в том виде, в каком его можно нарисовать: верхний регистр, многоточие — точками. */
export function normalizeText(text: string): string {
  return text.toUpperCase().replace(/…/g, '...');
}

export function glyphColumns(ch: string): Uint8Array {
  const key = ALIASES[ch] ?? ch;
  return GLYPHS.get(key) ?? GLYPHS.get('?')!;
}
